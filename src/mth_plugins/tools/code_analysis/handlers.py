"""Handlers for Python source analysis tools."""

from __future__ import annotations

import ast
import re
from pathlib import Path
from typing import Any

_COMPLEXITY_KEYWORDS = ("if", "elif", "for", "while", "try", "except")


def _py_files(root: Path) -> list[Path]:
    return list(root.rglob("*.py"))


def _read_text(path: Path) -> str | None:
    try:
        return path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return None


def handle_code_metrics(args: dict[str, Any]) -> str:
    path = args.get("path", ".")
    root = Path(path)
    py_files = _py_files(root)

    total_lines = blank_lines = comment_lines = 0
    function_count = class_count = file_count = complexity_total = 0

    for py_file in py_files:
        file_count += 1
        text = _read_text(py_file)
        if text is None:
            continue
        lines = text.splitlines()
        total_lines += len(lines)
        blank_lines += sum(1 for line in lines if line.strip() == "")
        comment_lines += sum(1 for line in lines if line.strip().startswith("#"))
        for line in lines:
            stripped = line.strip()
            if stripped.startswith("class "):
                class_count += 1
            elif stripped.startswith("def ") and not line.startswith((" ", "\t")):
                function_count += 1
        for keyword in _COMPLEXITY_KEYWORDS:
            complexity_total += len(re.findall(rf"\b{keyword}\b", text))

    metrics = {
        "file_count": file_count,
        "total_lines": total_lines,
        "blank_lines": blank_lines,
        "comment_lines": comment_lines,
        "net_lines": total_lines - blank_lines - comment_lines,
        "function_count": function_count,
        "class_count": class_count,
        "estimated_complexity": complexity_total,
    }
    return f"Code metrics for {path}:\n" + "\n".join(
        f"  {k}: {v}" for k, v in metrics.items()
    )


def handle_find_duplicates(args: dict[str, Any]) -> str:
    path = args.get("path") or "."
    min_lines = int(args.get("min_lines", 3))
    root = Path(path)

    file_lines: dict[Path, list[str]] = {}
    for f in _py_files(root):
        text = _read_text(f)
        if text is not None:
            file_lines[f] = text.splitlines()

    seen: dict[str, list[tuple[Path, int]]] = {}
    for f, lines in file_lines.items():
        for start in range(len(lines) - min_lines + 1):
            block = "\n".join(lines[start : start + min_lines])
            seen.setdefault(block, []).append((f, start + 1))

    duplicates = [
        f"Duplicate block ({min_lines} lines):\n"
        + "\n".join(f"  {loc[0].name}:{loc[1]}" for loc in locations[:5])
        + f"\n  {block[:100]}...\n"
        for block, locations in seen.items()
        if len(locations) > 1
    ]
    if not duplicates:
        return "No duplicate code blocks found."
    return f"Found {len(duplicates)} duplicate code blocks:\n" + "\n".join(
        duplicates
    )  # pragma: no cover


def handle_generate_docs(args: dict[str, Any]) -> str:
    path = args.get("path", ".")
    root = Path(path)
    docs = [
        f"# Auto-generated Documentation for {path}",
        "",
        "_Generated by mth-plugins recursive improvement tools_",
        "",
    ]

    for py_file in _py_files(root):
        text = _read_text(py_file)
        if text is None:
            continue
        try:
            tree = ast.parse(text)
        except SyntaxError:
            continue
        docs.append(f"## {py_file.name}")
        docs.append("")
        for node in ast.iter_child_nodes(tree):
            if isinstance(node, ast.ClassDef):
                class_doc = ast.get_docstring(node) or ""
                docs.append(f"### {node.name}")
                docs.append(f"*{class_doc}*" if class_doc else "_No docstring_")
                docs.append("")
                for item in node.body:
                    if isinstance(item, ast.FunctionDef):
                        doc = ast.get_docstring(item) or ""
                        docs.append(f"- **{item.name}(...)**")
                        docs.append(f"  *{doc}*" if doc else "  _No docstring_")
                        docs.append("")
            elif isinstance(node, ast.FunctionDef):
                doc = ast.get_docstring(node) or ""
                docs.append(f"- **{node.name}(...)**")
                docs.append(f"  *{doc}*" if doc else "  _No docstring_")
                docs.append("")
    return "\n".join(docs)
